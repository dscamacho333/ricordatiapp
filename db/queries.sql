# Get All Info related to User & User Account

SELECT
	*
FROM
	USER u
INNER JOIN
	ACCOUNT ac ON u.account_id = ac.id
INNER JOIN
	ACCOUNT_STATUS acs ON ac.account_status_id = acs.id;